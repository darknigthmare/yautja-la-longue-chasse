"""Measure incident props without altering pixels or existing art catalogues."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image

ART = Path(__file__).resolve().parent
ROOT = ART.parents[3]
RUNTIME = ROOT / 'public/game/clan-ship/incidents-v1'
JOBS = json.loads((ART / 'generation-jobs.json').read_text())


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


assets = []
catalogue = {}
failures = []
missing = []
prior_hashes = set()
for manifest_path in [ART.parent / 'manifest.json', ART.parent / 'actors/manifest.json']:
    prior_hashes.update(asset['decodedRgbaSha256'] for asset in json.loads(manifest_path.read_text())['assets'])

pixel_hashes = set(prior_hashes)
for job in JOBS['items']:
    slug = job['slug']
    source = ART / 'sources' / f'{slug}.png'
    runtime = RUNTIME / f'{slug}.png'
    if not source.exists() or not runtime.exists():
        missing.append(job['key'])
        continue
    with Image.open(runtime) as raw:
        raw.verify()
    with Image.open(runtime) as raw:
        mode = raw.mode
        im = raw.convert('RGBA')
    width, height = im.size
    alpha = im.getchannel('A')
    histogram = alpha.histogram()
    bounds = alpha.point(lambda value: 255 if value > 8 else 0).getbbox()
    border = sum(sum(part.histogram()[9:]) for part in (
        alpha.crop((0, 0, width, 1)), alpha.crop((0, height-1, width, height)),
        alpha.crop((0, 1, 1, height-1)), alpha.crop((width-1, 1, width, height-1)),
    ))
    digest = hashlib.sha256(im.tobytes()).hexdigest()
    if not bounds or not histogram[0] or not sum(histogram[9:]):
        failures.append(f'{slug}: missing visible pixels or transparency')
        continue
    if border:
        failures.append(f'{slug}: {border} visible border pixels')
    if digest in pixel_hashes:
        failures.append(f'{slug}: duplicate decoded image in this or previous lot')
    pixel_hashes.add(digest)
    if sha(source) != sha(runtime):
        failures.append(f'{slug}: source/runtime mismatch')
    original = Path(job['generationSource'])
    original_equal = sha(original) == sha(source) if original.exists() else None
    if original_equal is False:
        failures.append(f'{slug}: original generation/source mismatch')
    left, top, right, bottom = bounds
    measured = {
        'src': f'/game/clan-ship/incidents-v1/{slug}.png',
        'sourceWidth': width,
        'sourceHeight': height,
        'alphaBounds': {'x': left, 'y': top, 'width': right-left, 'height': bottom-top},
        'pivot': {'x': (left+right)/2, 'y': bottom-1, 'method': 'visible-bottom-center'},
        'humanArtValidation': False,
    }
    catalogue[job['key']] = measured
    assets.append({
        'key': job['key'], 'label': job['label'], **measured,
        'source': str(source.relative_to(ROOT)), 'runtime': str(runtime.relative_to(ROOT)),
        'sha256': sha(runtime), 'decodedRgbaSha256': digest,
        'bytes': runtime.stat().st_size, 'pngMode': mode,
        'originalGenerationEquality': original_equal,
        'alpha': {
            'threshold': 8, 'minimum': alpha.getextrema()[0], 'maximum': alpha.getextrema()[1],
            'fullyTransparentPixels': histogram[0], 'visiblePixels': sum(histogram[9:]),
            'visibleBorderPixels': border,
        },
        'prompt': job['prompt'], 'requirements': job['requirements'],
        'replacementFixture': job['fixture'], 'room': job['room'],
        'plannedPlacement': job['placement'], 'maximumDisplay': job['display'],
        'existingCollision': job['existingCollision'], 'addsCollision': False,
        'classification': 'original-game-adaptation',
        'nativePoses': 1, 'animationClips': 0,
        'bakedIndicators': 'unlit; runtime controls lamps and labels',
        'generation': 'complete', 'technicalValidation': 'passed' if border == 0 else 'failed',
        'sceneValidation': 'pending', 'physicalPivotValidation': 'pending',
        'canonicalFidelity': 'not-claimed',
    })

manifest = {
    'formatVersion': 1, 'date': JOBS['date'], 'basisCommit': JOBS['basisCommit'],
    'generatedAssets': len(assets), 'plannedAssets': len(JOBS['items']),
    'remainingGenerationKeys': missing, 'failures': failures,
    'runtimeBytes': sum(asset['bytes'] for asset in assets),
    'pixelEditing': 'none; runtime PNG is an exact copy of selected image_gen output',
    'previousLotDecodedImagesCheckedForDuplicates': len(prior_hashes),
    'humanArtValidation': False, 'assets': assets,
}
(ART / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
(RUNTIME / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
ts = '// Generated by production/excel-bible-20261108/art/incidents/verify-incidents.py.\n'
ts += '// Original neutral props; measured pivots are not human art or physical-contact validation.\n'
ts += 'export const CLAN_SHIP_INCIDENT_ART = '+json.dumps(catalogue, ensure_ascii=False, indent=2)+' as const;\n'
ts += 'export type ClanShipIncidentArtKey = keyof typeof CLAN_SHIP_INCIDENT_ART;\n'
(ROOT / 'app/game/clanShipIncidentArt.ts').write_text(ts)
print(json.dumps({'generated': len(assets), 'remaining': missing, 'runtimeBytes': manifest['runtimeBytes'], 'failures': failures}, ensure_ascii=False))
if failures or missing:
    raise SystemExit(1)
