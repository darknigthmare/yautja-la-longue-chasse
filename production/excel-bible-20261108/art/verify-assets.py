"""Inspect generated PNGs and publish measured metadata. Does not edit pixels."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image

ART = Path(__file__).resolve().parent
ROOT = ART.parents[2]
RUNTIME = ROOT / 'public/game/companions/quarters-v1'
JOBS = json.loads((ART / 'generation-jobs.json').read_text())


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


assets = []
catalogue = {}
missing = []
failures = []
pixel_hashes = set()

for job in JOBS['items']:
    slug = job['slug']
    source = ART / 'sources' / f'{slug}.png'
    runtime = RUNTIME / f'{slug}.png'
    if not source.exists() or not runtime.exists():
        missing.append(job['key'])
        continue
    with Image.open(runtime) as raw:
        raw.verify()
    with Image.open(runtime) as raw:
        original_mode = raw.mode
        im = raw.convert('RGBA')
    width, height = im.size
    alpha = im.getchannel('A')
    histogram = alpha.histogram()
    visible = alpha.point(lambda value: 255 if value > 8 else 0)
    bounds = visible.getbbox()
    border = sum(
        sum(part.histogram()[9:])
        for part in (
            alpha.crop((0, 0, width, 1)),
            alpha.crop((0, height - 1, width, height)),
            alpha.crop((0, 1, 1, height - 1)),
            alpha.crop((width - 1, 1, width, height - 1)),
        )
    )
    digest = hashlib.sha256(im.tobytes()).hexdigest()
    if not bounds or not histogram[0] or not sum(histogram[9:]):
        failures.append(f'{slug}: missing visible pixels or effective transparency')
        continue
    if border:
        failures.append(f'{slug}: {border} visible border pixels at alpha > 8')
    if sha(source) != sha(runtime):
        failures.append(f'{slug}: source and runtime differ')
    if digest in pixel_hashes:
        failures.append(f'{slug}: duplicate decoded image')
    pixel_hashes.add(digest)
    left, top, right, bottom = bounds
    measured = {
        'src': f'/game/companions/quarters-v1/{slug}.png',
        'sourceWidth': width,
        'sourceHeight': height,
        'alphaBounds': {'x': left, 'y': top, 'width': right-left, 'height': bottom-top},
        'pivot': {'x': (left+right)/2, 'y': bottom-1, 'method': 'visible-bottom-center'},
        'humanArtValidation': False,
    }
    catalogue[job['key']] = measured
    assets.append({
        'key': job['key'],
        'label': job['label'],
        **measured,
        'source': str(source.relative_to(ROOT)),
        'runtime': str(runtime.relative_to(ROOT)),
        'sha256': sha(runtime),
        'decodedRgbaSha256': digest,
        'bytes': runtime.stat().st_size,
        'pngMode': original_mode,
        'alpha': {
            'threshold': 8,
            'minimum': alpha.getextrema()[0],
            'maximum': alpha.getextrema()[1],
            'fullyTransparentPixels': histogram[0],
            'visiblePixels': sum(histogram[9:]),
            'visibleBorderPixels': border,
        },
        'prompt': f'prompts/{slug}.txt',
        'requirements': job['requiredBy'],
        'textReferences': job['textReferences'],
        'classification': 'original-game-adaptation',
        'nativePoses': 1,
        'animationClips': 0,
        'generation': 'complete',
        'technicalValidation': 'passed' if border == 0 else 'failed',
        'sceneValidation': 'pending',
        'physicalPivotValidation': 'pending',
        'canonicalFidelity': 'not-claimed',
    })

manifest = {
    'formatVersion': 1,
    'date': JOBS['date'],
    'basisCommit': JOBS['basisCommit'],
    'generatedAssets': len(assets),
    'plannedAssets': len(JOBS['items']),
    'remainingGenerationKeys': missing,
    'runtimeBytes': sum(item['bytes'] for item in assets),
    'pixelEditing': 'none; runtime PNG is an exact copy of selected image_gen output',
    'occupancyContract': 'Render module only for a recruited companion assigned to this vessel with installation complete. Occupant is separate and absent while deployed.',
    'humanArtValidation': False,
    'failures': failures,
    'assets': assets,
}
(ART / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
(RUNTIME / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
ts = '// Generated by production/excel-bible-20261108/art/verify-assets.py.\n'
ts += '// Measured visible bounds/pivots are not human art or physical-contact validation.\n'
ts += 'export const COMPANION_QUARTER_ART = '+json.dumps(catalogue, ensure_ascii=False, indent=2)+' as const;\n'
ts += 'export type CompanionQuarterArtKey = keyof typeof COMPANION_QUARTER_ART;\n'
(ROOT / 'app/game/companionQuarterArt.ts').write_text(ts)
print(json.dumps({'generated': len(assets), 'remaining': missing, 'runtimeBytes': manifest['runtimeBytes'], 'failures': failures}, ensure_ascii=False))
if failures or missing:
    raise SystemExit(1)
