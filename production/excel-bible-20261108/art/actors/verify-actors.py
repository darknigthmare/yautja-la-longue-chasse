"""Inspect original actor PNGs, then publish bounds and static runtime metadata.

This reads but never resizes, crops, recolors or edits pixels. The existing
Eclisse import remains independently traceable to its source commit.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image

ART = Path(__file__).resolve().parent
ROOT = ART.parents[3]
RUNTIME = ROOT / 'public/game/companions/actors-v1'
JOBS = json.loads((ART / 'generation-jobs.json').read_text())
ECLISSE = json.loads((ART.parents[1] / 'compagnons/eclisse-import.json').read_text())


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


catalogue = {'eclisse': ECLISSE['asset']}
assets = []
failures = []
missing = []
pixel_hashes = set()

if sha(ROOT / ECLISSE['destination']) != ECLISSE['sha256']:
    failures.append('eclisse: existing imported bytes differ from provenance')

for job in JOBS['items']:
    key = job['key']
    source = ART / 'sources' / f'{key}.png'
    runtime = RUNTIME / f'{key}.png'
    if not source.exists() or not runtime.exists():
        missing.append(key)
        continue
    with Image.open(runtime) as raw:
        raw.verify()
    with Image.open(runtime) as raw:
        mode = raw.mode
        im = raw.convert('RGBA')
    width, height = im.size
    alpha = im.getchannel('A')
    histogram = alpha.histogram()
    bounds = alpha.point(lambda value: 255 if value > 8 else 0).getbbox()
    border = sum(sum(part.histogram()[9:]) for part in (
        alpha.crop((0, 0, width, 1)),
        alpha.crop((0, height - 1, width, height)),
        alpha.crop((0, 1, 1, height - 1)),
        alpha.crop((width - 1, 1, width, height - 1)),
    ))
    digest = hashlib.sha256(im.tobytes()).hexdigest()
    if not bounds or not histogram[0] or not sum(histogram[9:]):
        failures.append(f'{key}: missing visible pixels or effective transparency')
        continue
    if border:
        failures.append(f'{key}: {border} visible border pixels at alpha > 8')
    if sha(source) != sha(runtime):
        failures.append(f'{key}: source and runtime differ')
    if digest in pixel_hashes:
        failures.append(f'{key}: duplicate decoded image')
    pixel_hashes.add(digest)
    left, top, right, bottom = bounds
    measured = {
        'src': f'/game/companions/actors-v1/{key}.png',
        'sourceWidth': width,
        'sourceHeight': height,
        'alphaBounds': {'x': left, 'y': top, 'width': right-left, 'height': bottom-top},
        'pivot': {'x': (left+right)/2, 'y': bottom-1, 'method': 'visible-bottom-center'},
        'motionStatus': 'static-draft',
        'humanArtValidation': False,
    }
    catalogue[key] = measured
    assets.append({
        'key': key,
        'label': job['name'],
        **measured,
        'nativeFacing': job['nativeFacing'],
        'source': str(source.relative_to(ROOT)),
        'runtime': str(runtime.relative_to(ROOT)),
        'sha256': sha(runtime),
        'decodedRgbaSha256': digest,
        'bytes': runtime.stat().st_size,
        'pngMode': mode,
        'alpha': {
            'threshold': 8,
            'minimum': alpha.getextrema()[0],
            'maximum': alpha.getextrema()[1],
            'fullyTransparentPixels': histogram[0],
            'visiblePixels': sum(histogram[9:]),
            'visibleBorderPixels': border,
        },
        'prompt': job['prompt'],
        'requirements': job['requiredBy'],
        'references': job['sources'],
        'classification': 'original-game-adaptation',
        'nativePoses': 1,
        'animationClips': 0,
        'generation': 'complete',
        'technicalValidation': 'passed' if border == 0 else 'failed',
        'sceneValidation': 'pending',
        'physicalPivotValidation': 'pending',
        'canonicalFidelity': 'not-claimed',
    })

manifest = {
    'formatVersion': 1,
    'date': JOBS['date'],
    'basisCommit': JOBS['basisCommit'],
    'generatedAssets': len(assets),
    'plannedAssets': len(JOBS['items']),
    'remainingGenerationKeys': missing,
    'runtimeBytes': sum(item['bytes'] for item in assets),
    'pixelEditing': 'none; runtime PNG is an exact copy of selected image_gen output',
    'humanArtValidation': False,
    'failures': failures,
    'existingImports': [{
        'key': 'eclisse',
        'runtime': ECLISSE['destination'],
        'provenance': 'production/excel-bible-20261108/compagnons/eclisse-import.json',
        'sha256': ECLISSE['sha256'],
        'bytes': (ROOT / ECLISSE['destination']).stat().st_size,
        'generatedThisBatch': False,
    }],
    'assets': assets,
}
(ART / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
(RUNTIME / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
ts = '// Generated by production/excel-bible-20261108/art/actors/verify-actors.py.\n'
ts += '// Static art; measured pivots are not human art or physical-contact validation.\n'
ts += 'export const COMPANION_PILOT_ART = '+json.dumps(catalogue, ensure_ascii=False, indent=2)+' as const;\n'
(ROOT / 'app/game/companionPilotArt.ts').write_text(ts)
print(json.dumps({'generated': len(assets), 'existingImports': 1, 'remaining': missing, 'runtimeBytes': manifest['runtimeBytes'], 'failures': failures}, ensure_ascii=False))
if failures or missing:
    raise SystemExit(1)
