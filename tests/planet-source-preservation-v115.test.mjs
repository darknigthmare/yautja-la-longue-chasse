import assert from "node:assert/strict";
import test from "node:test";
import {execFileSync} from "node:child_process";
import {readFile} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import {createHash} from "node:crypto";
import {build} from "esbuild";

// Compare with the actual source before this lint cleanup. The CI must fetch
// this immutable Git object; unavailable evidence is a failure, never a skip.
const referenceCommit="e1e45fbf85d843c26ac1bf4f816baf46313795b0";
const modulePath="app/game/systems/clanWarPlanetGeneratorV115.ts";
const root=fileURLToPath(new URL("../",import.meta.url));
const resolveDir=fileURLToPath(new URL("../app/game/systems/",import.meta.url));
const original=execFileSync("git",["show",referenceCommit+":"+modulePath],{cwd:root,encoding:"utf8",maxBuffer:1048576});
const current=await readFile(new URL("../"+modulePath,import.meta.url),"utf8");
async function apiFor(source){
  const bundle=await build({stdin:{contents:source+'\nexport {WAR_PLANET_RECIPE_FIELDS_V103} from "./clanWarPlanetGeneratorV103";\n',
    resolveDir,loader:"ts"},bundle:true,write:false,format:"esm",platform:"node",target:"es2022",logLevel:"silent"});
  return import("data:text/javascript;base64,"+Buffer.from(bundle.outputFiles[0].text).toString("base64"));
}
const before=await apiFor(original),after=await apiFor(current);
const digest=value=>createHash("sha256").update(JSON.stringify(value)).digest("hex");
const extras=["planetSize","islandShape","continentShape","regionShape","landMaterial","liquidMaterial"];

test("the V103 projection preserves every published field, excludes all six V115 modules and never changes its source",()=>{
  const recipe=after.normalizeWarPlanetRecipeV115({seed:0xffffffff,planetSize:"colossal",islandShape:39,continentShape:38,
    regionShape:37,landMaterial:15,liquidMaterial:14,territoryCount:18,regionCount:3});
  const original=JSON.stringify(recipe);
  const projected=after.projectWarPlanetRecipeV103FromV115(recipe);
  assert.equal(projected.version,103);
  assert.deepEqual(Object.keys(projected),["version",...after.WAR_PLANET_RECIPE_FIELDS_V103]);
  for(const field of after.WAR_PLANET_RECIPE_FIELDS_V103)assert.deepEqual(projected[field],recipe[field],field);
  for(const field of extras)assert.equal(Object.hasOwn(projected,field),false,field);
  assert.equal(JSON.stringify(recipe),original);
  assert.equal(recipe.version,115);
  for(const field of extras)assert.ok(Object.hasOwn(recipe,field));
});

test("six radii and two geographic formats preserve exact V115 codes, full generated bytes, summaries and legacy V103 dispatch inputs",()=>{
  for(const planetSize of ["dwarf","small","terran","large","giant","colossal"]){
    for(const format of [
      {seed:11521,territoryCount:18,regionCount:3,landform:"archipelago",islandShape:0,continentShape:1,regionShape:2,landMaterial:0,liquidMaterial:1},
      {seed:0xffffffff,territoryCount:24,regionCount:4,landform:"continents",islandShape:39,continentShape:38,regionShape:37,landMaterial:15,liquidMaterial:14},
    ]){
      const recipe=before.normalizeWarPlanetRecipeV115({...format,planetSize});
      const code=before.encodeWarPlanetV115(recipe),world=before.generateWarPlanetV115(recipe);
      assert.equal(after.encodeWarPlanetV115(recipe),code,planetSize);
      assert.deepEqual(after.parseWarPlanetV115(code),before.parseWarPlanetV115(code));
      assert.equal(digest(after.generateWarPlanetV115(recipe)),digest(world),planetSize+" complete world at "+referenceCommit);
      assert.deepEqual(after.describeWarPlanetV115(code),before.describeWarPlanetV115(code));
      assert.deepEqual(after.generatedWarPlanetV115(code).procedural.recipe,recipe);
    }
  }
});
