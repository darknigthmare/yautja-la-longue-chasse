import assert from "node:assert/strict";
import test from "node:test";
import {build} from "esbuild";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
const names=["clanWarOperationsV115","clanWarOuterPaceV144","clanWarOuterRouteProgressV140",
 "clanWarOuterWeightedProgressV141","clanWarTravelLedgerV145","clanWarOuterRerouteV144",
 "clanWarOuterIncidentV143","clanWarParallelModesV137","clanWarParallelModesV138","clanWarOuterChoicesV142","clanWarBibleV6"];
const built=await build({stdin:{contents:names.map(n=>"export * from './app/game/systems/"+n+"';").join("\n"),
 resolveDir:process.cwd()},bundle:true,write:false,platform:"node",format:"esm",target:"es2022"});
const api=await import("data:text/javascript;base64,"+Buffer.from(built.outputFiles[0].text).toString("base64"));
const rules=api.DEFAULT_WAR_RULES_V6;
function mission(){
 const initial=api.createWarOperationsV115(rules),team=initial.teams[0];
 const site=rules.territories.find(t=>t.id!==initial.baseId&&!api.warMissionEligibleV115(initial,rules,t.id,[team.id]));
 assert.ok(site);const start=api.beginWarOperationV115(initial,"outer",site.id,[team.id],rules,1000);
 assert.equal(start.accepted,true,start.message);return start.state;
}
test("force pace preserves exact position and advances continuously on the actual V6 passages",()=>{
 const before=mission(),order=before.outer[0],when=order.startedAt+1000;
 const old=api.warOuterWeightedProgressV141(order,when,rules);
 const cmd=api.commandWarOuterPaceV144(before,order.id,when,rules);
 assert.equal(cmd.accepted,true,cmd.message);
 const after=cmd.state.outer[0],at=api.warOuterWeightedProgressV141(after,when,rules);
 assert.equal(cmd.state.rav,before.rav-3);assert.equal(after.dueAt,order.dueAt-8000);
 assert.equal(at.legProgress,old.legProgress);assert.equal(at.currentPassageId,old.currentPassageId);
 assert.equal(at.currentPassageProgress,old.currentPassageProgress);
 let previous=at.legProgress;
 for(let t=when+1;t<after.dueAt;t+=1000){
  const p=api.warOuterWeightedProgressV141(after,t,rules);
  assert.ok(p.legProgress>=previous&&p.legProgress<1);previous=p.legProgress;
 }
 assert.equal(api.warOuterWeightedProgressV141(after,after.dueAt,rules).phase,"arrived");
 assert.equal(api.simulateWarOuterMissionV115(cmd.state,after,rules).threat,
  api.simulateWarOuterMissionV115(before,order,rules).threat+2);
 assert.equal(api.settleWarOuterOpsV115(cmd.state,after.dueAt-1,rules).accepted,false);
 assert.equal(api.settleWarOuterOpsV115(cmd.state,after.dueAt,rules).accepted,true);
});
test("forced pace survives save, recall and cannot be combined with other route changes",()=>{
 const s=mission(),o=s.outer[0],time=o.startedAt+1000;
 const fast=api.commandWarOuterPaceV144(s,o.id,time,rules);assert.equal(fast.accepted,true);
 assert.deepEqual(api.readWarOperationsV115(JSON.stringify(fast.state),rules),fast.state);
 assert.equal(api.orderWarOuterReconHaltV137(fast.state,o.id,time+1,rules).accepted,false);
 assert.equal(api.commandWarOuterIncidentV143(fast.state,o.id,"detour",time+1,rules).accepted,false);
 assert.equal(api.commandWarOuterRerouteV144(fast.state,o.id,o.routeIds,time+1,rules).accepted,false);
 const recalled=api.recallWarOuterMissionV116(fast.state,o.id,time+1000,rules);
 assert.equal(recalled.accepted,true,recalled.message);
 assert.deepEqual(api.readWarOperationsV115(JSON.stringify(recalled.state),rules),recalled.state);
 assert.equal(api.settleWarOuterOpsV115(recalled.state,recalled.state.outer[0].dueAt,rules).accepted,true);
 for(const patch of [{paidRav:0},{savedMs:1},{orderedAt:o.startedAt-1},{originalDueAt:o.dueAt+1}]){
  const forged={...fast.state,outer:[{...fast.state.outer[0],forcedPace:{...fast.state.outer[0].forcedPace,...patch}}]};
  assert.equal(api.readWarOperationsV115(JSON.stringify(forged),rules),null);
 }
});
test("halt, incident, diversion, insufficient RAV and late orders cannot be accelerated",()=>{
 const s=mission(),o=s.outer[0],at=o.startedAt+1000;
 assert.equal(api.commandWarOuterPaceV144({...s,rav:2},o.id,at,rules).accepted,false);
 assert.equal(api.commandWarOuterPaceV144(s,o.id,o.startedAt+Math.ceil((o.dueAt-o.startedAt)/3),rules).accepted,false);
 const halted=api.orderWarOuterReconHaltV137(s,o.id,at,rules);
 assert.equal(halted.accepted,true,halted.message);
 assert.equal(api.commandWarOuterPaceV144(halted.state,o.id,at+1,rules).accepted,false);
 const diverted={...s,outer:[{...o,routeDiversion:{fromPassageIds:o.routeIds,originalDueAt:o.dueAt,changedAt:at,paidRav:1}}]};
 assert.equal(api.commandWarOuterPaceV144(diverted,o.id,at+1,rules).accepted,false);
});
test("archives generated by the real PR57 runtime retain paid pace and recall on this branch",()=>{
 const directory="tests/fixtures/outer-pace-pr57/";
 const metadata=JSON.parse(readFileSync(directory+"provenance.json","utf8"));
 for(const [name,sha] of [["outer-pr57-paced.json",metadata.pacedSha256],
  ["outer-pr57-paced-recall.json",metadata.recalledSha256]]){
  const bytes=readFileSync(directory+name);
  assert.equal(createHash("sha256").update(bytes).digest("hex"),sha);
  const source=JSON.parse(bytes),loaded=api.readWarOperationsV115(bytes.toString(),rules);
  assert.deepEqual(loaded,source,name);
  assert.equal(loaded.outer[0].forcedPace.paidRav,3);
  assert.equal(loaded.rav,metadata.afterPaceRav);
  assert.equal(api.settleWarOuterOpsV115(loaded,loaded.outer[0].dueAt,rules).accepted,true);
 }
});
test("field bulletin waits for actual halfway progress after pace acceleration",()=>{
 const s=mission(),o=s.outer[0],at=o.startedAt+Math.floor((o.dueAt-o.startedAt)/4);
 const fast=api.commandWarOuterPaceV144(s,o.id,at,rules);
 assert.equal(fast.accepted,true,fast.message);
 const changed=fast.state.outer[0],elapsed=Math.ceil((changed.dueAt-changed.startedAt)/2);
 const nominalHalf=changed.startedAt+elapsed;
 assert.ok(api.warOuterWeightedProgressV141(changed,nominalHalf,rules).legProgress<.5);
 assert.equal(api.requestWarOuterSignalV138(fast.state,o.id,nominalHalf,rules).accepted,false);
 let reached=nominalHalf;
 while(api.warOuterWeightedProgressV141(changed,reached,rules).legProgress<.5)reached++;
 const signal=api.requestWarOuterSignalV138(fast.state,o.id,reached,rules);
 assert.equal(signal.accepted,true,signal.message);
 assert.ok(api.readWarOperationsV115(JSON.stringify(signal.state),rules));
});
