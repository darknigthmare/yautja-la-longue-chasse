import fs from "node:fs/promises";
import assert from "node:assert/strict";
import { buildPitArenaRuntimeData } from "./build-pit-arena-runtime-v33.mjs";
const arenaId=process.argv[2];
assert(/^[a-z0-9-]+$/.test(arenaId));
const proof=`docs/v34-${arenaId}-renderer-qa.json`;
const qa=JSON.parse(await fs.readFile(proof,"utf8"));
assert.equal(qa.result,"PASS");assert.equal(qa.arenaId,arenaId);
assert.equal(qa.loaded.independentKit,true);assert.equal(qa.loaded.images,14);
assert.deepEqual(qa.errors,[]);assert.deepEqual(qa.failedRequests,[]);
assert(qa.scenarios.length>=8 && qa.scenarios.every(s=>s.missing.length===0&&s.unchangedState&&s.unchangedCamera));
const file="art-source/v33/pit-arenas/production-manifest.json";
const manifest=JSON.parse(await fs.readFile(file,"utf8"));
const stage=manifest.stages.find(s=>s.legacyRuntimeArenaId===arenaId);
assert(stage?.legacyRuntimeStatus==="playable");assert.equal(stage.planes.flatMap(p=>p.assets.flatMap(a=>a.frames)).length,14);
stage.runtimeEnabled=true;
await fs.writeFile(file,JSON.stringify(manifest,null,2)+"\n");
await fs.appendFile(`docs/v34-${arenaId}-art-review.md`,`\n## Revue de composition\n\nLes captures centre, rapprochée et coins gauche/droit du renderer réel ont été inspectées après chargement des 14 PNG. Le sol reste droit sous les combattants, les supports restent assis sur leur niveau, les lampes restent suspendues et les ouvertures sont transparentes. La recette ${proof} valide six plans, huit scénarios et le cadrage mobile, sans erreur ni changement du combat/caméra. Le kit est activé après cette revue. Les images restent au statut reviewed tant que la recette de l'application complète n'est pas archivée.\n`);
await buildPitArenaRuntimeData();
console.log(JSON.stringify({arenaId,runtimeEnabled:true,images:14,status:"reviewed",rendererProof:proof}));
