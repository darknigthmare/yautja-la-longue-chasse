import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { homeworldQaModelV64 } from './homeworld-qa-model-v64.mjs';
import { homeworldNavigatorV66 } from './homeworld-navigation-browser-v66.mjs';
import { firstTracksCompleted, p } from '../tests/helpers/solo-v67-campaign-route.mjs';
const url = process.env.V70_QA_URL ?? 'http://127.0.0.1:4187';
const output = process.env.V70_ATLAS_QA_OUTPUT ?? 'work-local/v70/qa/atlas';
await fs.mkdir(output, { recursive: true });
const api = homeworldQaModelV64(process.cwd(), ['homeworldCity.ts', 'homeworldInteriorsV64.ts', 'homeworldSpatialCodex.ts', 'homeworldAtlasRoutesV70.ts']);
const save = firstTracksCompleted();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const checks = [], captures = [], errors = [], failures = [];
page.setDefaultTimeout(60000);
page.on('pageerror', e => errors.push(e.message));
page.on('response', r => { if (r.status() >= 400) failures.push({ url: r.url(), status: r.status() }); });
const capture = async name => { const path = output + '/' + name + '.jpg'; await page.screenshot({ path, type: 'jpeg', quality: 90 }); captures.push(path); };
const saved = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), p.SAVE_STORAGE_KEY);
try {
  await page.addInitScript(({ key, save }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(save)); }, { key: p.SAVE_STORAGE_KEY, save });
  await page.goto(url, { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /^Continuer/ }).click();
  await page.locator('[data-homeworld-hub]').waitFor();
  assert.equal(await page.locator('main').getAttribute('data-game-content-version'), 'V70');
  await page.clock.install(); await page.clock.pauseAt(await page.evaluate(() => Date.now() + 150));
  const nav = homeworldNavigatorV66(page, api);
  await nav.focus();
  await page.getByRole('button', { name: /^Atlas de la cité/ }).click();
  await page.locator('[data-homeworld-atlas-regions]').click();
  const frozen = await page.locator('[data-homeworld-viewport]').getAttribute('data-city-seconds');
  const original = await saved(), position = await nav.position();
  for (const destination of api.HOMEWORLD_ATLAS_ROUTES_V70) {
    await page.locator('[data-homeworld-atlas-site="' + destination.id + '"]').click();
    await page.getByRole('button', { name: 'Tracer le chemin à pied' }).click();
    assert.equal(await page.locator('[data-homeworld-route-status]').getAttribute('data-homeworld-route-status'), 'reachable');
    assert.equal(await page.locator('[data-homeworld-atlas-access]').getAttribute('data-homeworld-atlas-access'), destination.regionId === 'forbidden-reserve' ? 'locked' : 'open');
    assert.equal(await page.locator('[data-homeworld-atlas-threshold]').count(), 10);
    if (['ash-marches', 'thermal-caves', 'forbidden-reserve'].includes(destination.regionId)) await capture(destination.regionId + '-atlas');
    checks.push({ name: 'threshold-route-and-real-access', region: destination.regionId });
  }
  await nav.tick(2000);
  assert.equal(await page.locator('[data-homeworld-viewport]').getAttribute('data-city-seconds'), frozen);
  assert.deepEqual(await nav.position(), position);
  assert.deepEqual(await saved(), original, 'atlas reads and route calculations are save-neutral');
  const target = api.HOMEWORLD_ATLAS_ROUTES_V70.find(r => r.regionId === 'thermal-caves');
  await page.locator('[data-homeworld-atlas-site="' + target.id + '"]').click();
  await page.getByRole('button', { name: 'Tracer le chemin à pied' }).click();
  await page.getByRole('button', { name: 'Suivre le repère' }).click();
  await nav.focus(); await nav.follow(api.homeworldSpatialRoute(position, target.approach).points);
  await nav.tick(500);
  assert.equal(await page.locator('[data-homeworld-route-guidance]').getAttribute('data-homeworld-route-guidance'), 'arrived');
  await capture('physical-threshold-arrival');
  checks.push({ name: 'physical-walking-to-threshold', region: target.regionId, position: await nav.position(), noTeleport: true });
  await page.setViewportSize({ width: 393, height: 852 });
  await page.getByRole('button', { name: /^Atlas de la cité/ }).click();
  await page.locator('[data-homeworld-atlas-regions]').click();
  await page.locator('[data-homeworld-atlas-site="route-forbidden-reserve"]').click();
  await capture('portrait-atlas-reserve-locked');
  assert.equal(await page.getByRole('dialog').evaluate(dialog => dialog.scrollWidth > dialog.clientWidth + 1), false);
  await page.keyboard.press('Escape'); await nav.tick(100);
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.deepEqual((await saved()).prologue.chronicle, original.prologue.chronicle);
  assert.deepEqual((await saved()).appearance, original.appearance);
  checks.push({ name: 'portrait-focus-pause-no-grants' });
  assert.deepEqual(errors, []); assert.deepEqual(failures, []);
  await fs.writeFile(output + '/report.json', JSON.stringify({ status: 'PASS', url, checks, captures, errors, failures, limits: 'The ten city routes are traced against real solids. One city route is physically walked by keyboard. The ten complete regional connectors are not all played in this recipe. First Tracks uses declared model-played prerequisites. No discovery, grant or teleport is produced by atlas reading.' }, null, 2));
  console.log(JSON.stringify({ status: 'PASS', checks: checks.length, captures: captures.length, output }));
} catch (error) {
  await capture('failure').catch(() => {});
  await fs.writeFile(output + '/report.json', JSON.stringify({ status: 'FAIL', url, checks, captures, errors, failures, error: String(error) }, null, 2));
  throw error;
} finally { await browser.close(); }
