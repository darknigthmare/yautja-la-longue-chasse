import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from 'playwright-core';
import {enterCampaignDeck} from './campaign-browser-helpers.mjs';
import {selectPitMatch} from './pit-selection-browser-helpers.mjs';
const base=process.env.V46_MOBILE_QA_URL||'http://127.0.0.1:4174';
const output=process.env.V46_MOBILE_QA_OUTPUT||'work/v46/mobile-accessibility-qa';
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const checks=[],errors=[],responses=[];
let page;
const watch=()=>{page.setDefaultTimeout(45000);page.on('pageerror',error=>errors.push(error.message));page.on('response',response=>{if(response.status()>=400)responses.push({url:response.url(),status:response.status()});});};
const within=async locator=>locator.evaluate(el=>{const r=el.getBoundingClientRect();return {x:r.x,right:r.right,width:r.width,height:r.height,viewport:innerWidth,inside:r.x>=-1&&r.right<=innerWidth+1};});
const noOverflow=()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth);
try{
 page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,reducedMotion:'no-preference'});watch();
 await page.goto(base,{waitUntil:'networkidle',timeout:120000});
 const create=page.getByRole('button',{name:/^Nouvelle partie/});await create.focus();await page.keyboard.press('Enter');
 await page.getByLabel('Nom du chasseur').fill('QA mobile V46');
 const enter=page.getByRole('button',{name:/^Créer la partie 1/});await enter.focus();await page.keyboard.press('Enter');
 await page.locator('[data-new-game-identity]').waitFor({timeout:60000});
 await page.getByRole('button',{name:'Confirmer le chasseur et ouvrir le premier briefing',exact:true}).focus();await page.keyboard.press('Enter');
 await page.locator('[data-first-hunt-briefing]').waitFor();assert(await noOverflow());
 checks.push({name:'new-player-keyboard-menu',viewport:390,newGameActivatedWithKeyboard:true,briefingWithinViewport:true});
 await page.getByRole('button',{name:'Commencer la première chasse guidée',exact:true}).focus();await page.keyboard.press('Enter');
 await page.locator('[data-first-hunt-guide]').waitFor({timeout:120000});
 const resume=page.getByRole('button',{name:'Reprendre la chasse',exact:true});if(await resume.count())await resume.click();
 const guide=page.locator('[data-first-hunt-guide]'),collapse=page.getByRole('button',{name:'Réduire le guide',exact:true});
 const guideBox=await within(guide),toggleBox=await within(collapse);
 assert(guideBox.inside);assert(toggleBox.height>=44&&toggleBox.width>=44);assert(await noOverflow());
 await guide.scrollIntoViewIfNeeded();await page.screenshot({path:output+'/guide-mobile.png'});
 await collapse.focus();await page.keyboard.press('Enter');
 await page.waitForFunction(()=>document.activeElement?.matches('canvas.hunt-canvas'));
 assert.equal(await page.getByRole('button',{name:'Développer le guide',exact:true}).getAttribute('aria-expanded'),'false');
 await page.keyboard.press('Escape');await page.getByRole('button',{name:'Reprendre la chasse',exact:true}).waitFor();
 assert.equal(await guide.count(),0);
 await page.getByRole('button',{name:'Reprendre la chasse',exact:true}).focus();await page.keyboard.press('Enter');
 await page.getByRole('button',{name:'Développer le guide',exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Développer le guide',exact:true}).getAttribute('aria-expanded'),'false');
 checks.push({name:'guide-mobile-focus-and-pause',guideBox,toggleBox,canvasFocusReturned:true,collapsedChoiceSurvivesPause:true});
 await page.close();
 page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,reducedMotion:'no-preference'});watch();
 await enterCampaignDeck(page,{url:base});await page.getByRole('button',{name:'THE PIT · combat',exact:true}).click();
 await page.getByRole('radio',{name:/^Versus local/}).click();
 await selectPitMatch(page,{player:'jungle-hunter',opponent:'city-hunter',arena:'the-pit'});
 await page.locator('[data-pit-match-loading]').waitFor({state:'detached'});
 const control=page.locator('[data-pit-camera-control]'),canvas=page.locator('canvas[data-pit-camera-mode]');
 const cameraBox=await within(control);assert(cameraBox.inside);assert(await noOverflow());
 assert.equal(await canvas.getAttribute('data-pit-camera-mode'),'follow');
 await control.focus();await page.keyboard.press('Enter');
 await page.waitForFunction(()=>document.querySelector('canvas[data-pit-camera-mode]')?.dataset.pitCameraMode==='fixed');
 await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Combat THE PIT');
 assert.equal(await control.getAttribute('aria-pressed'),'false');
 await control.tap();await page.waitForFunction(()=>document.querySelector('canvas[data-pit-camera-mode]')?.dataset.pitCameraMode==='follow');
 await page.screenshot({path:output+'/pit-camera-mobile.png'});
 const scrollPosition=await page.locator('[aria-label="Combat THE PIT"]').evaluate(el=>({pageY:scrollY,rootY:el.scrollTop,rootTop:el.getBoundingClientRect().top,headerTop:el.querySelector('header').getBoundingClientRect().top}));
 await page.locator('[aria-label="Combat THE PIT"]').evaluate(el=>el.scrollTo({top:0,behavior:'instant'}));
 const headerAccessibleAfterScroll=await page.locator('[aria-label="Combat THE PIT"] header').evaluate(el=>el.getBoundingClientRect().top>=0);assert(headerAccessibleAfterScroll);
 await page.screenshot({path:output+'/pit-camera-mobile-top.png'});
 checks.push({name:'camera-mobile-keyboard-and-touch',cameraBox,scrollPosition,headerAccessibleAfterScroll,keyboardToggle:true,touchToggle:true,focusReturnedToCombat:true,noHorizontalOverflow:true});
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>document.querySelector('canvas[data-pit-camera-mode]')?.dataset.pitCameraMode==='fixed');
 assert(await control.isDisabled());checks.push({name:'mobile-system-reduced-motion',cameraFixed:true,controlDisabled:true});
 assert.deepEqual(errors,[]);assert.deepEqual(responses,[]);
 const report={passed:true,checkedAt:new Date().toISOString(),base,checks,errors,responses,limits:['Chrome mobile emulation 390x844; no physical phone or screen reader certification.','Campaign creation uses real fresh isolated storage; THE PIT uses the existing legacy QA fixture in a separate context.']};
 await fs.writeFile(output+'/report.json',JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
}catch(error){if(page&&!page.isClosed()){await page.screenshot({path:output+'/failure.png',fullPage:true}).catch(()=>{});await fs.writeFile(output+'/failure.json',JSON.stringify({error:String(error),checks,errors,responses,body:await page.locator('body').innerText().catch(()=>null)},null,2));}throw error;}
finally{await browser.close();}
