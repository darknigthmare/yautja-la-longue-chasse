import fs from "node:fs/promises";
import assert from "node:assert/strict";

const arenaId = process.argv[2];
assert(/^arena-0(?:09|1[0-9]|20)-[a-z0-9-]+$/.test(arenaId));
const proof = `docs/v34-${arenaId}-renderer-qa.json`;
const qa = JSON.parse(await fs.readFile(proof, "utf8"));
assert.equal(qa.result, "PASS");
assert.equal(qa.arenaId, arenaId);
assert.equal(qa.conceptPreview, true);
assert.equal(qa.playablePromotion, false);
assert.equal(qa.applicationFlowVerified, false);
assert.equal(qa.loaded.independentKit, true);
assert.equal(qa.loaded.images, 14);
assert.equal(qa.loaded.expectedImages, 14);
assert.deepEqual(qa.loaded.failed, []);
assert.deepEqual(qa.errors, []);
assert.deepEqual(qa.failedRequests, []);
assert.equal(qa.mobileNoOverflow, true);
assert(qa.scenarios.length >= 8 && qa.scenarios.every(s => s.planes.length === 6 && s.missing.length === 0 && s.unchangedState && s.unchangedCamera));
const manifest = JSON.parse(await fs.readFile("art-source/v33/pit-arenas/production-manifest.json", "utf8"));
const stage = manifest.stages.find(s => s.catalogueId === arenaId);
assert.equal(stage?.legacyRuntimeStatus, "concept");
assert.equal(stage.legacyRuntimeArenaId, null);
assert.equal(stage.runtimeEnabled, false);
const frames = stage.planes.flatMap(p => p.assets.flatMap(a => a.frames));
assert.equal(frames.length, 14);
assert(frames.every(f => f.status === "reviewed" && f.integration === null));
const review = `docs/v34-${arenaId}-art-review.md`;
const marker = "## Revue de composition non jouable";
assert(!(await fs.readFile(review, "utf8")).includes(marker), "Revue déjà enregistrée");
await fs.appendFile(review, `\n${marker}\n\nLes captures centre, rapprochée et coins gauche/droit ont été inspectées avec les vrais PNG et deux combattants du projet. Sol et appuis sont cohérents, les ouvertures gardent leur transparence et les éléments suspendus conservent leur ancrage. La recette ${proof} valide six plans, huit scénarios et le cadrage mobile, sans erreur ni changement du combat ou de la caméra. Cette prévisualisation utilise uniquement dans le harnais la géométrie de THE PIT comme gabarit de contrôle. Elle ne valide ni le level design final ni un accès dans le jeu : statut concept, aucun identifiant d'arène runtime, runtimeEnabled=false, images reviewed et integration=null sont conservés.\n`);
console.log(JSON.stringify({ arenaId, images: 14, status: "reviewed-concept", runtimeEnabled: false, rendererProof: proof }));
