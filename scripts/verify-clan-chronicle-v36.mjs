import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { chromium } from "playwright-core";
import { build } from "esbuild";

const base = process.env.V36_QA_URL || "http://localhost:4174";
const output = process.env.V36_QA_OUTPUT || "work/v36/browser-qa";
await fs.mkdir(output, { recursive: true });
const bundle = await build({ entryPoints: ["app/game/save.ts"], bundle: true, platform: "node", format: "esm", write: false });
const api = await import("data:text/javascript;base64," + Buffer.from(bundle.outputFiles[0].text).toString("base64"));
const fixture = api.defaultSave("2026-09-15T12:00:00.000Z");
fixture.profile.hunterName = "Archive de contrôle";
fixture.profile.honor = 1900;
fixture.profile.rankId = "elder";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const errors = [], failedRequests = [], checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  await context.addInitScript(({ key, save }) => {
    if (!sessionStorage.getItem("v36-qa-seeded")) {
      localStorage.setItem(key, JSON.stringify(save));
      sessionStorage.setItem("v36-qa-seeded", "true");
    }
  }, { key: api.SAVE_STORAGE_KEY, save: fixture });
  const page = await context.newPage();
  page.on("pageerror", e => errors.push(e.message));
  page.on("response", r => { if (r.status() >= 400) failedRequests.push({ url: r.url(), status: r.status() }); });
  await page.goto(base, { waitUntil: "networkidle", timeout: 120000 });
  await page.locator('[data-game-content-version="V36"]').waitFor();
  const storedBefore = await page.evaluate(() => JSON.stringify(Object.fromEntries(Object.entries(localStorage).sort())));
  await page.getByRole("button", { name: "Dossier de campagne", exact: true }).click();
  const panel = page.locator('[data-clan-chronicle="design-v36"]');
  await panel.waitFor();
  await page.locator('[data-chronicle-legacy-rank="elder"]').waitFor();
  assert.match(await panel.innerText(), /Parcours en conception, pas encore jouable/);
  assert.match(await panel.innerText(), /1900 honneur/);
  assert.equal(await page.locator("[data-chronicle-rite]").count(), 7);
  await page.locator('[data-chronicle-rite="nursery-recognition"] summary').click();
  const nursery = await page.locator('[data-chronicle-rite="nursery-recognition"]').innerText();
  assert.doesNotMatch(nursery, /Premières Pistes/);
  await page.screenshot({ path: output + "/journey-desktop.png" });
  checks.push("Historical Elder recognition preserved; nursery does not require a later hunt; all seven rites clearly unfinished.");
  await page.getByRole("button", { name: "Mondes et réserves", exact: true }).click();
  assert.match(await panel.innerText(), /Surface noire/);
  assert.match(await panel.innerText(), /Korthas/);
  assert.equal(await panel.locator("article").count(), 15);
  checks.push("Five Homeworld families and ten proposed preserves visible; original dark-surface/underground-forest rule retained.");
  await page.getByRole("button", { name: "100 proies · fiches de conception", exact: true }).click();
  assert.equal(await page.locator("[data-human-concept]").count(), 100);
  const search = page.getByRole("searchbox", { name: "Rechercher par identifiant, profil ou arme" });
  await search.fill("h001");
  assert.equal(await page.locator("[data-human-concept]").count(), 1);
  await page.locator('[data-human-concept="H001"]').waitFor();
  await search.fill("zzzz-no-result");
  await page.getByRole("button", { name: "Effacer la recherche" }).click();
  assert.equal(await page.locator("[data-human-concept]").count(), 100);
  await search.fill("eclaireuse");
  assert(await page.locator("[data-human-concept]").count() > 0, "Accent-insensitive search should find éclaireuse.");
  checks.push("All 100 text profiles present; exact ID, accent-insensitive search and empty-result recovery verified.");
  await page.setViewportSize({ width: 390, height: 844 });
  await search.fill("H100");
  await search.press("Tab");
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute("data-human-concept")), "H100", "Human cards must be focusable for keyboard and shared gamepad scrolling.");
  await page.screenshot({ path: output + "/humans-mobile.png", fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "Mobile page must not overflow horizontally.");
  await page.getByRole("button", { name: "Retour au menu", exact: true }).click();
  await page.getByRole("button", { name: "Jouer", exact: true }).waitFor();
  const storedAfter = await page.evaluate(() => JSON.stringify(Object.fromEntries(Object.entries(localStorage).sort())));
  assert.equal(storedAfter, storedBefore, "Dossier consultation must not change any saved data.");
  checks.push("390px layout has no horizontal overflow; returning to menu leaves all localStorage bytes unchanged.");
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole("button", { name: "Jouer", exact: true }).click();
  await page.getByRole("button", { name: "THE PIT · combat", exact: true }).waitFor();
  checks.push("Existing adult campaign still opens its ship with THE PIT access.");
  assert.deepEqual(errors, []);
  assert.deepEqual(failedRequests, []);
  const report = { url: base, version: "V36", checkedAt: new Date().toISOString(), checks, errors, failedRequests, limitations: ["No playable youth chapter or new art claimed.", "No physical controller or PC package verification in this run."] };
  await fs.writeFile(output + "/verification.json", JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
