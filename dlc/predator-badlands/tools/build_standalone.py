#!/usr/bin/env python3
"""Rebuild the delivered HTML offline; never fetch, install or upload anything."""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

EXPECTED = "f8be31ce49b3a1a6c7aa40c7cce0f974216e76ae16ab308e2c9d1b2e6b52f3f6"
SOURCE_HASHES = {
    "JOUER_PREDATOR_BADLANDS.html": "8291233f2511d1ef2ebf08959b9451631f6a2fd6bb70ddae8022fd0d68468ae9",
    "styles/badlands.css": "f73a0c97437f0ebdc8ec8056c1d1a28c67af9d491cf6da11f757f0fa727ac6e1",
    "src/badlands-data.js": "05fe27cdc9c44e76f9b38d29ff8a22a4dbd1b14fde2acbc49f1d06585dcf435d",
    "src/badlands-game.js": "985bec074b50e2e6dcdf6fc1643f0751beeebb1a555b1c22602fd02458d3f15f",
}

def rebuild(root: Path) -> bytes:
    sources = {}
    for name, expected in SOURCE_HASHES.items():
        raw = (root / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != expected:
            raise ValueError(f"Original source changed: {name}; refusing to label it v0.1.0.")
        sources[name] = raw.decode("utf-8")
    output = sources["JOUER_PREDATOR_BADLANDS.html"]
    for tag, name, opening, closing in (
        ('<link rel="stylesheet" href="styles/badlands.css">', "styles/badlands.css", "<style>", "</style>"),
        ('<script src="src/badlands-data.js"></script>', "src/badlands-data.js", "<script>", "</script>"),
        ('<script src="src/badlands-game.js"></script>', "src/badlands-game.js", "<script>", "</script>"),
    ):
        if output.count(tag) != 1:
            raise ValueError(f"Expected exactly one reference: {name}")
        output = output.replace(tag, opening + sources[name] + closing, 1)
    raw = output.encode("utf-8")
    if hashlib.sha256(raw).hexdigest() != EXPECTED:
        raise ValueError("Rebuilt HTML does not match the original delivery.")
    return raw

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify byte-exact reproducibility in memory, without writing.")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1] / "v0.1.0"
    raw = rebuild(root)
    target = root / "JOUER_PREDATOR_BADLANDS_STANDALONE.html"
    if target.exists() and target.read_bytes() != raw:
        raise SystemExit("Refusing to overwrite a different existing standalone HTML.")
    if not args.check and not target.exists():
        with target.open("xb") as stream:
            stream.write(raw)
    print(f"PASS: standalone reproducible, {len(raw)} bytes, SHA256 {EXPECTED}")
    print("No screenshot, archive or v0.2 asset is generated by this command.")

if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as exc:
        raise SystemExit(str(exc)) from exc
